// Generates server/routes.gen.ts: a static map of "METHOD path" -> endpoint handle(), from src/endpoints/**/name_METHOD.ts.
// Floot served endpoints/jobs/create_POST.ts at POST /_api/jobs/create; this keeps those URLs unchanged.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const dir = join(root, "src/endpoints");
const files = [];
const walk = (d) => {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (/_(GET|POST)\.ts$/.test(f)) files.push(p);
  }
};
walk(dir);
files.sort();

const lines = [
  "// GENERATED by scripts/gen-api-routes.mjs. Do not edit; run `npm run gen:routes`.",
  "type Handler = (request: Request) => Promise<Response> | Response;",
];
const entries = [];
files.forEach((file, i) => {
  const rel = relative(join(root, "server"), file).split(sep).join("/").replace(/\.ts$/, "");
  const m = relative(dir, file).split(sep).join("/").match(/^(.*)_(GET|POST)\.ts$/);
  lines.push(`import { handle as h${i} } from "${rel.startsWith(".") ? rel : "./" + rel}";`);
  entries.push(`  "${m[2]} ${m[1]}": h${i},`);
});
lines.push("export const routes: Record<string, Handler> = {", ...entries, "};", "");
writeFileSync(join(root, "server/routes.gen.ts"), lines.join("\n"));
console.log(`gen-api-routes: ${files.length} endpoints`);
